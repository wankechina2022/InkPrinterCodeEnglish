namespace InkPrinterCode.Model
{
    /// <summary>
    /// [2026-09-10] 码数据的喷印状态枚举
    ///
    /// 【取值约定】数值与数据库 CodeData.PrintStatus 列一一对应，落库存的是 int 值：
    ///   0 = 未喷（NotPrinted）：导入后的初始状态，阶段二喷码时按 Id 顺序取这批数据
    ///   1 = 已喷（Printed）   ：[2026-09-10 取码占用制] 从库中取出码的瞬间即标为此状态（占用），
    ///                           之后才写入喷码机；写入失败也不回退（宁可漏喷，绝不重喷）
    ///   2 = 失败（Failed）    ：发送或喷印失败（重试次数记在 RetryCount）
    ///   3 = 作废（Voided）    ：人工判定不再使用的码
    ///
    /// 【边界】数值一旦上线不可改动 —— 库里已有历史数据按这套数值存储；
    ///         新增状态只能往后追加（4、5……），不得复用或调整已有数值。
    ///
    /// 【业务约束】数据查看页的删除功能禁止删除 NotPrinted（0）状态的记录，
    ///             未喷的码属于待生产资源，误删会直接造成生产数据缺失。
    /// </summary>
    public enum PrintStatus
    {
        /// <summary>未喷（0）—— 导入后的初始状态</summary>
        NotPrinted = 0,

        /// <summary>
        /// 已喷（1）—— [2026-09-10 取码占用制] 从数据库取出的瞬间即标为此状态（占用锁），
        /// 取码条件恒为 PrintStatus = 0，故同一条码不可能被二次取出，从根上杜绝重复喷印。
        /// 写入喷码机失败也不回退（A 方案：宁可漏喷，绝不重喷）；一个码只写一次、不重试。
        /// </summary>
        Printed = 1,

        /// <summary>失败（2）—— 发送或喷印失败</summary>
        Failed = 2,

        /// <summary>作废（3）—— 人工判定不再使用</summary>
        Voided = 3
    }
}
